describe("parseSvgLayers", () => {
  test("names the default KiCad colours in stack order and lists the rest by hex", () => {
    const layers = parseSvgLayers(KICAD_SVG);
    expect(layers.map((l) => l.name)).toEqual([
      "Edge.Cuts",
      "F.Cu",
      "B.Cu",
      "F.SilkS",
      "Holes",
      "#123ABC",
    ]);
    // Case-insensitive: `#c83434` and `#C83434` are one layer.
    expect(layers.find((l) => l.name === "F.Cu")?.count).toBe(2);
    // Group + child + a stroke use.
    expect(layers.find((l) => l.name === "B.Cu")?.count).toBe(3);
  });

  test("ignores the root group's black defaults and stroke-width/fill-opacity declarations", () => {
    expect(parseSvgLayers(KICAD_SVG).some((l) => l.color === "#000000")).toBe(false);
    expect(parseSvgLayers(`<svg><g style="stroke-width:0.2; fill-opacity:1"></g></svg>`)).toEqual(
      [],
    );
  });
});

describe("applySvgLayers", () => {
  test("returns the same string when nothing is hidden", () => {
    expect(applySvgLayers(KICAD_SVG, new Set())).toBe(KICAD_SVG);
  });

  test("turns a hidden colour into none wherever it is used, in either case, without touching the others", () => {
    const out = applySvgLayers(KICAD_SVG, new Set(["#C83434", "#123ABC"]));
    expect(out).not.toMatch(/#c83434/i);
    expect(out).not.toContain("#123ABC");
    expect(out).toContain(
      'fill:none; fill-opacity:1.0000; stroke:none;fill-rule:evenodd;" d="M 104.2200',
    );
    expect(out).toContain('fill="none"');
    expect(out).toContain("fill:#4D7FC4");
    expect(out).toContain("stroke:#F2EDA1");
    // Hiding never changes the drawing's size or element count.
    expect(out.length).toBeLessThan(KICAD_SVG.length);
    expect((out.match(/<path/g) ?? []).length).toBe((KICAD_SVG.match(/<path/g) ?? []).length);
  });

  test("a stroke-only layer goes too", () => {
    const out = applySvgLayers(KICAD_SVG, new Set(["#D0D2CD"]));
    expect(out).toContain("stroke:none; stroke-width:0.0500");
  });
});

describe("svgSize", () => {
  test("prefers the viewBox, then width/height with units stripped", () => {
    expect(svgSize(KICAD_SVG)).toEqual({ width: 297.0022, height: 210.0072 });
    expect(svgSize(`<svg width="100mm" height="50mm"></svg>`)).toEqual({ width: 100, height: 50 });
    expect(svgSize(`<svg viewBox="0,0,10,5" width="1" height="1"/>`)).toEqual({
      width: 10,
      height: 5,
    });
  });

  test("is null for a size it cannot read", () => {
    expect(svgSize(`<svg></svg>`)).toBeNull();
    expect(svgSize("not svg")).toBeNull();
    expect(svgSize(`<svg viewBox="0 0 0 0" width="0" height="0"/>`)).toBeNull();
  });
});

test("fitSize contains the drawing in the box on the limiting axis", () => {
  expect(fitSize({ width: 200, height: 100 }, { width: 100, height: 100 })).toEqual({
    width: 100,
    height: 50,
  });
  expect(fitSize({ width: 100, height: 200 }, { width: 100, height: 100 })).toEqual({
    width: 50,
    height: 100,
  });
});

test("prepareSvgForNative strips the prolog, metadata and KiCad's invisible text", () => {
  const out = prepareSvgForNative(KICAD_SVG);
  expect(out.startsWith("<svg")).toBe(true);
  expect(out).not.toContain("<title>");
  expect(out).not.toContain("<desc>");
  expect(out).not.toContain("<text");
  expect(out).not.toContain("DOCTYPE");
  // The stroked glyph outlines that draw the reference stay.
  expect(out).toContain('class="stroked-text"');
});

test("svgRenderPath hands very large drawings to the WebView", () => {
  expect(svgRenderPath(KICAD_SVG)).toBe("native");
  expect(svgRenderPath("x".repeat(SVG_NATIVE_MAX_CHARS + 1))).toBe("webview");
});

test("svgWebViewHtml inlines the svg on the requested background and allows pinch-zoom", () => {
  const html = svgWebViewHtml(KICAD_SVG, "#001023");
  expect(html).toContain("user-scalable=yes");
  expect(html).toContain("background:#001023");
  expect(html).toContain("<svg");
  expect(html).not.toContain("<?xml");
});

export function glossaryTerm(locale: AppLocale, id: GlossaryTermId): string {
  const entry = GLOSSARY.find((item) => item.id === id);
  return entry?.translations[locale] ?? entry?.en ?? id;
}

export function glossaryById(): Record<GlossaryTermId, GlossaryEntry> {
  return Object.fromEntries(GLOSSARY.map((entry) => [entry.id, entry])) as Record<GlossaryTermId, GlossaryEntry>;
}

/** Every shipped locale has a translation for every term (used by the consistency test). */
export function glossaryCoverage(): { locale: AppLocale; id: GlossaryTermId }[] {
  const missing: { locale: AppLocale; id: GlossaryTermId }[] = [];
  for (const entry of GLOSSARY) {
    for (const locale of APP_LOCALES) {
      const value = entry.translations[locale];
      if (!value || value.trim() === "") missing.push({ locale, id: entry.id });
    }
  }
  return missing;
}

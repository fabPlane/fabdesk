import { expect, test } from "bun:test";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import type { CoreEvent } from "@fabdesk/protocol";
import { createRegistry } from "../src";
import { schematicFocusAnchors, verifySchematicFocusFrame } from "../src/schematic-focus";
import { mockServices, tempProject, contextFactory } from "./mock-services";
const native = '(kicad_sch (paper "User" 170 660) (lib_symbols (symbol "Fake" (property "Reference" "U1") (at 999 999))) (symbol (lib_id "RF_Module:ESP32") (at 85 300 90) (unit 1) (property "Reference" "U1") (property "Value" "ESP32-S3") (instances (project "board" (path "/root" (reference "U1"))))))';
const svg = '<svg width="169.9768mm" height="659.9936mm" viewBox="0 0 169.9768 659.9936"><desc>Image generated by Eeschema-SVG</desc></svg>';
const hash = (s: string) => createHash("sha256").update(s).digest("hex");
test("saved root symbols, not library definitions, establish component origins", () => {
  expect(schematicFocusAnchors(native, "U1")).toEqual({ value: "ESP32-S3", points: [{ x: 85, y: 300, unit: 1 }], page: { width: 170, height: 660 } });
  expect(() => schematicFocusAnchors(native, "U99")).toThrow("not found");
  expect(() => schematicFocusAnchors(native.replace('(at 85 300 90)', '(at 900 300 90)'), "U1")).toThrow("outside");
  expect(() => schematicFocusAnchors(native.replace('(reference "U1")', '(reference "U201")'), "U1")).toThrow("Instance-specific");
  expect(() => schematicFocusAnchors(native.replace('(unit 1)', '(unit 0)'), "U1")).toThrow("outside");
  expect(() => schematicFocusAnchors(native.slice(0, -1), "U1")).toThrow("Malformed");
  expect(() => schematicFocusAnchors(native.replace('"ESP32-S3"', '"unterminated'), "U1")).toThrow("Malformed");
});
test("millimetre page frame rejects cropped, scaled and unrelated previews", () => {
  expect(() => verifySchematicFocusFrame(svg, { width: 170, height: 660 })).not.toThrow();
  for (const changed of [svg.replace('viewBox="0 0', 'viewBox="5 0'), svg.replace('169.9768 659.9936', '1699.768 6599.936'), svg.replace('Eeschema-SVG', 'other'), svg.replace('169.9768mm', '169.9768px')]) expect(() => verifySchematicFocusFrame(changed, { width: 170, height: 660 })).toThrow("frame");
});
async function fixture(editDuringExport = false, sheets = 1) {
  const project = await tempProject("component-focus"); await writeFile(`${project.dir}/board.kicad_sch`, native);
  const base = mockServices([project]), hierarchy = await base.kicad.inspectSchematicHierarchy({ path: "mock", version: "mock" }, { projectDir: project.dir, rootSchematic: `${project.dir}/board.kicad_sch` });
  hierarchy.sheets[0]!.sha256 = hash(native); if (sheets > 1) hierarchy.sheets.push({ ...hierarchy.sheets[0]!, nativePath: "child.kicad_sch" });
  const events: CoreEvent[] = [];
  const services = mockServices([project], { bus: { emit: e => events.push(e) }, kicad: { ...base.kicad, inspectSchematicHierarchy: async (_cli, options) => { expect(options.ownedFilesOnly).toBe(true); return hierarchy; }, exportOwnedSchematicSvg: async () => {
    if (editDuringExport) await writeFile(`${project.dir}/board.kicad_sch`, native + "\n");
    return { sourceRevision: hierarchy.aggregateRevision, sourceFiles: [{ path: "board.kicad_sch", sha256: hash(native) }], sheets: [{ name: "board.svg", svg: new TextEncoder().encode(svg) }] };
  } } });
  const registry = createRegistry(), factory = contextFactory(services, project);
  const call = () => registry.invoke("schematic_focus", { reference: "U1" }, () => factory({ def: registry.get("schematic_focus")!, signal: new AbortController().signal, progress() {} }));
  return { project, events, call };
}
test("tool binds source/preview bytes and emits a request without pretending the client displayed it", async () => {
  const { project, events, call } = await fixture(); const result = await call();
  expect(result.isError).not.toBe(true); expect(result.text).toContain("Display is not confirmed");
  const event = events.find(e => e.topic === "project.schematic_focus"); if (event?.topic !== "project.schematic_focus") throw new Error("focus event missing");
  expect(event.focus).toMatchObject({ reference: "U1", sourceSha256: hash(native), svgSha256: hash(svg), projectId: project.id });
  expect(await readFile(`${project.dir}/${event.focus.svgPath}`, "utf8")).toBe(svg);
  expect(await readFile(`${project.dir}/board.kicad_sch`, "utf8")).toBe(native);
});
test("source changes during export and ambiguous sheet ownership never emit focus", async () => {
  for (const [changed, count] of [[true, 1], [false, 2]] as const) {
    const { call, events } = await fixture(changed, count);
    await expect(call()).rejects.toThrow(changed ? "changed" : "one complete root sheet");
    expect(events.some(e => e.topic === "project.schematic_focus")).toBe(false);
  }
});

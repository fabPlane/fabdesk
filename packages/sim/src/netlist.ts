import type { NetlistFile } from "@fabdesk/protocol";
import type { SimAnalysis } from "./types";

/**
 * SPICE netlist (with `.END`) from the design source. Two-terminal parts are wired by pin order
 * (`1` → `2`, or the first two pins sorted naturally); the net named GND/0/VSS is ground; a pin no
 * net names gets its own floating node. Reference prefixes decide the element: R, C, L by value
 * (SPICE suffixes as written), V/I sources (`DC <value>`, `AC 1` added by `ensureAcStimulus` for AC
 * runs), D with a default model. Anything else (ICs, connectors) is left out with a comment, so a
 * netlist is always produced and the result says what it ignores.
 */
export function spiceNetlist(file: NetlistFile): string {
  return `${spiceElements(file)}\n.END\n`;
}

const GROUND = new Set(["GND", "0", "VSS", "AGND", "DGND"]);

function nodeName(net: string): string {
  return GROUND.has(net.toUpperCase()) ? "0" : net.replace(/[^A-Za-z0-9_]/g, "_").toUpperCase();
}

function spiceValue(raw: string): string {
  // "4.7k" -> 4.7K, "100nF" -> 100N, "5V" -> 5, "1 uF" -> 1U; SPICE ignores unit letters after the multiplier.
  const m = /^\s*([-+]?\d*\.?\d+(?:e[-+]?\d+)?)\s*([a-zA-Zµ]*)/.exec(raw);
  if (!m) return raw.trim().toUpperCase() || "0";
  const [, num, unit] = m;
  const u = (unit ?? "").replace("µ", "u").toLowerCase();
  const suffix = u.startsWith("meg") ? "MEG" : /^[tgmkunpf]/.test(u) ? u[0]!.toUpperCase() : "";
  return `${num}${suffix}`;
}

/** The element lines only (no `.END`), one per component that SPICE can model. */
export function spiceElements(file: NetlistFile): string {
  const { components, nets } = file.netlist;
  const nodeOf = new Map<string, string>();
  for (const net of nets) for (const n of net.nodes) nodeOf.set(`${n.ref}/${n.pin}`, nodeName(net.name));
  const pinsOf = new Map<string, string[]>();
  for (const net of nets) for (const n of net.nodes) pinsOf.set(n.ref, [...(pinsOf.get(n.ref) ?? []), n.pin]);
  const lines: string[] = ["* generated by fabdesk from circuit.netlist.json"];
  let needDiodeModel = false;
  const natural = (a: string, b: string) => a.localeCompare(b, undefined, { numeric: true });
  for (const c of [...components].sort((a, b) => natural(a.ref, b.ref))) {
    const kind = c.ref.replace(/[^A-Za-z].*$/, "").toUpperCase();
    const pins = [...new Set(pinsOf.get(c.ref) ?? [])].sort(natural);
    const node = (pin: string) => nodeOf.get(`${c.ref}/${pin}`) ?? `NC_${c.ref}_${pin}`.toUpperCase();
    const [a, b] = [pins[0] ?? "1", pins[1] ?? "2"];
    switch (kind) {
      case "R":
      case "C":
      case "L":
        lines.push(`${kind}${c.ref} ${node(a)} ${node(b)} ${spiceValue(c.value)}`);
        break;
      case "V":
        lines.push(`V${c.ref} ${node(a)} ${node(b)} DC ${spiceValue(c.value)}`);
        break;
      case "I":
        lines.push(`I${c.ref} ${node(a)} ${node(b)} DC ${spiceValue(c.value)}`);
        break;
      case "D":
        needDiodeModel = true;
        lines.push(`D${c.ref} ${node(a)} ${node(b)} DDEFAULT`);
        break;
      default:
        lines.push(`* ${c.ref} (${c.value}) omitted: no SPICE model for ${kind || "this"} components`);
    }
  }
  if (needDiodeModel) lines.push(".MODEL DDEFAULT D");
  return lines.join("\n");
}

/** Netlist body without the trailing `.END` so analysis/control lines can be appended. */
export function netlistBody(netlist: string): string {
  return netlist
    .split("\n")
    .filter((line) => !/^\s*\.end\s*$/i.test(line))
    .join("\n")
    .trimEnd();
}

/** Dot-command for an analysis (shared by spicey and ngspice). */
export function analysisLine(analysis: SimAnalysis): string {
  switch (analysis.kind) {
    case "op":
      return ".op";
    case "tran":
      return `.tran ${fmt(analysis.stepS)} ${fmt(analysis.stopS)}`;
    case "ac":
      return `.ac dec ${analysis.pointsPerDecade} ${fmt(analysis.startHz)} ${fmt(analysis.stopHz)}`;
  }
}

/**
 * AC analysis needs a small-signal stimulus. The emitter writes DC-only sources, so when no
 * independent voltage source carries an `AC` term, the first one gets `AC 1`.
 */
export function ensureAcStimulus(body: string): string {
  const lines = body.split("\n");
  const hasAc = lines.some((l) => /^v\S*\s/i.test(l) && /\bac\b/i.test(l));
  if (hasAc) return body;
  const index = lines.findIndex((l) => /^v\S*\s/i.test(l));
  if (index === -1) return body;
  lines[index] = `${lines[index]} AC 1`;
  return lines.join("\n");
}

export function fmt(value: number): string {
  return Number.isFinite(value) ? value.toExponential(6).replace(/\.?0+e/, "e") : String(value);
}

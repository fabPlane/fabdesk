import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

export interface AgentDocsContext {
  projectName: string;
  /** Tool cheat-sheet rendered by `@fabdesk/tools`' agent-docs adapter. */
  toolsMarkdown: string;
  /** Absolute paths of sketch images attached to the project/run. */
  sketches: string[];
  board: { layers: number; widthMm?: number; heightMm?: number; template?: string };
  mcpServerName: string;
}

/** Design rules for prefab blanks, keyed by `fabdesk.json` `board.template`. */
const TEMPLATE_NOTES: Record<string, string> = {
  "viagrid-9055": `## Viagrid 9055 blank (board.template)
This board is laid out on Opulo's Viagrid 9055: a prefabricated 90 × 55 mm two-layer blank with **180 factory
vias** and four 3.5 mm mounting holes. Copper is removed afterwards to isolate nets, so:
- Render \`<Viagrid9055Blank />\` inside \`<board>\` (\`import { Viagrid9055Blank } from "./viagrid-9055"\`). Do not edit viagrid-9055.tsx.
- **Never place your own \`<via>\`.** Layer changes happen only through the factory vias; the router (laser-prefab
  preset) chooses them and claims them for the net. A route result with vias "OFF the grid" is a failure.
- Factory vias sit in rows at y = ±20.5 (x = −35…35 step 2), columns at x = ±38 (y = −14…14 step 2), and two
  clusters centred on x = ±19 (y = ±8, ±10, ±12 rows plus a small diamond at y = 0). Free areas for parts:
  x in −12…12, or |x| > 26 with |y| < 14. Keep 2 mm from the mounting holes at (±38.75, ±18.25).
- Prefer 0805 or larger SMD parts and 0.2 mm traces (blank rules: track 0.2 mm, clearance 0.2 mm).
- After routing run \`verify_viagrid\`; fix placement in circuit.tsx and re-route until it passes.`,
};

export const USER_START = "<!-- fabdesk:user-start -->";
export const USER_END = "<!-- fabdesk:user-end -->";
const HEADER =
  "<!-- generated by fabdesk — regenerated before every agent run. Keep your own notes inside the user section below; everything else is overwritten. -->";
const DEFAULT_USER_SECTION =
  "<!-- Add project notes for the agent here. This section survives regeneration. -->";

function boardSize(board: AgentDocsContext["board"]): string {
  if (board.widthMm !== undefined && board.heightMm !== undefined)
    return `${board.widthMm} × ${board.heightMm} mm`;
  if (board.widthMm !== undefined) return `${board.widthMm} mm wide (height free)`;
  if (board.heightMm !== undefined) return `${board.heightMm} mm high (width free)`;
  return "not fixed — keep it as small as the parts allow";
}

/** Renders AGENTS.md; `userSection` is the preserved text between the user markers. */
export function renderAgentsMd(
  ctx: AgentDocsContext,
  userSection: string = DEFAULT_USER_SECTION,
): string {
  const mcp = ctx.mcpServerName;
  const sketches =
    ctx.sketches.length > 0
      ? ctx.sketches
          .map((p) => `- \`${p}\` — read it with your file/image reading tool before designing.`)
          .join("\n")
      : "- No sketches attached. Work from the prompt.";
  const tools =
    ctx.toolsMarkdown.trim() === ""
      ? "_No tool documentation available for this run._"
      : ctx.toolsMarkdown.trim();

  return `${HEADER}
# ${ctx.projectName} — fabPlane project

This directory is a fabPlane PCB project. fabPlane runs you with an MCP server named \`${mcp}\`
(tools appear as \`mcp__${mcp}__<tool>\` or \`${mcp}__<tool>\`). Use those tools to build, route,
convert, check and render the board; only edit files listed as yours in the file contract.

## Board constraints
- Copper layers: ${ctx.board.layers}
- Size: ${boardSize(ctx.board)}
- Every net must be routed and DRC must be clean before you report the board as done.
${ctx.board.template && TEMPLATE_NOTES[ctx.board.template] ? `\n${TEMPLATE_NOTES[ctx.board.template]}\n` : ""}
## Sketches
${sketches}

## File contract
| Path | Owner | Notes |
| --- | --- | --- |
| \`fabdesk.json\` | fabdesk | Project manifest. Never edit. |
| \`circuit.tsx\` | **you** | tscircuit source: the single file you write. Components, footprints, nets, placement hints. |
| \`circuit.json\` | \`${mcp}\` | Circuit JSON produced by the build tool. Never edit; rebuild instead. |
| \`circuit.routed.json\` | \`${mcp}\` | Output of the router. Never edit. |
| \`board.kicad_pcb\`, \`board.kicad_sch\`, \`board.kicad_pro\` | \`${mcp}\` | Generated KiCad files. Never hand-edit; regenerate. |
| \`sketches/\` | user | Input drawings and photos (read-only). |
| \`renders/\` | \`${mcp}\` | PNG/SVG renders of the board and schematic. |
| \`reports/\` | \`${mcp}\` | \`drc.json\`, \`erc.json\`, \`checks.json\`, \`spice.json\` from the check tools. |
| \`exports/\` | \`${mcp}\` | Gerbers, BOM, pick-and-place. |
| \`AGENTS.md\`, \`CLAUDE.md\` | fabdesk | Regenerated per run except the user section. |

## Workflow
1. Read the sketches and the prompt; read \`circuit.tsx\` if it exists.
2. Write or edit \`circuit.tsx\` (valid tscircuit; keep footprints and net names explicit).
3. Build with the \`${mcp}\` build tool; fix every error and rebuild until it passes.
4. Route with the routing tool, then convert to KiCad.
5. Run DRC/ERC; fix the source (not the generated files) and repeat from step 3 while anything fails.
6. Render, then summarise what the board does, the parts used and any open issues. Render tools attach
   images directly in chat and return a \`fileUrl\` / \`url\` field. When the user asks for links, give
   those browser-openable \`file://\` URLs as plain text.

Work through the \`${mcp}\` tools: they are the only tools guaranteed to be available. Shell commands
(Bash, PowerShell, python, node) may be blocked by the permission mode and cannot be approved during a run;
if one is refused, do not retry it, use a \`${mcp}\` tool instead (project_read_file, circuit_query,
route_status, ...). \`circuit.json\`, \`circuit.routed.json\`, \`board.kicad_*\` and \`reports/\` are outputs
of earlier runs, not inputs: start from \`circuit.tsx\` and rebuild rather than reading old results.

Do not run \`git\`, install packages, or touch files outside this directory unless the prompt asks for it.

## Tools
${tools}

${USER_START}
${userSection.trim() === "" ? DEFAULT_USER_SECTION : userSection.trim()}
${USER_END}
`;
}

/** Extracts the preserved user section from an existing AGENTS.md, if any. */
export function extractUserSection(existing: string | undefined): string | undefined {
  if (existing === undefined) return undefined;
  const start = existing.indexOf(USER_START);
  if (start < 0) return undefined;
  const end = existing.indexOf(USER_END, start + USER_START.length);
  if (end < 0) return undefined;
  return existing.slice(start + USER_START.length, end).trim();
}

/** Writes `AGENTS.md` (preserving the user section) and `CLAUDE.md` (`@AGENTS.md`) into `projectDir`. */
export async function writeAgentDocs(projectDir: string, ctx: AgentDocsContext): Promise<void> {
  const agentsPath = join(projectDir, "AGENTS.md");
  const claudePath = join(projectDir, "CLAUDE.md");
  let existing: string | undefined;
  try {
    existing = await readFile(agentsPath, "utf8");
  } catch {
    existing = undefined;
  }
  const userSection = extractUserSection(existing);
  const rendered =
    userSection !== undefined ? renderAgentsMd(ctx, userSection) : renderAgentsMd(ctx);
  if (rendered !== existing) await writeFile(agentsPath, rendered, "utf8");
  const claudeMd = "@AGENTS.md\n";
  let existingClaude: string | undefined;
  try {
    existingClaude = await readFile(claudePath, "utf8");
  } catch {
    existingClaude = undefined;
  }
  if (existingClaude !== claudeMd) await writeFile(claudePath, claudeMd, "utf8");
}

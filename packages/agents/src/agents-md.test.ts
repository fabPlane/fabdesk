import { describe, expect, test } from "bun:test";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  extractUserSection,
  renderAgentsMd,
  USER_END,
  BOARD_WORKFLOW_MD,
  USER_START,
  writeAgentDocs,
  type AgentDocsContext,
} from "./agents-md";

const ctx: AgentDocsContext = {
  projectName: "Blinky",
  toolsMarkdown: "### circuit_build\nBuilds circuit.netlist.json.",
  sketches: ["/tmp/p/sketches/front.png"],
  board: { layers: 2, widthMm: 50, heightMm: 30 },
  mcpServerName: "fabdesk",
};

describe("renderAgentsMd", () => {
  test("renders ordinary project context without advertising experimental IPC", () => {
    const md = renderAgentsMd(ctx);
    expect(md.startsWith("<!-- generated by fabdesk")).toBe(true);
    expect(md).toContain("# Blinky — fabPlane project");
    expect(md).toContain("Copper layers: 2");
    expect(md).toContain("50 × 30 mm");
    expect(md).toContain("`/tmp/p/sketches/front.png`");
    expect(md).toContain("Its MCP server is `fabdesk`");
    expect(md).not.toContain("fabpcb ipc");
    expect(md).toContain("| `board.kicad_pcb` | Canonical KiCad PCB. |");
    expect(md).toContain("Both authoring paths are available");
    expect(md).toContain("`circuit.netlist.json`");
    expect(md).toContain("`route_status`");
    expect(md).toContain("`$KICAD_CLI`");
    expect(md).not.toContain("### circuit_build");
    expect(md).toContain("`project.parts.json`");
    expect(md).toContain("## Off-board parts");
    expect(md).toContain("parts_search");
    expect(md).toContain("## Shopping list");
    expect(md).toContain("`/shopping-list`");
    expect(md).toContain("shopping_list_sync_bom");
    expect(md).not.toMatch(
      /workflow|must use|should use|prefer|retry|repeat until|run .* first|stopping policy/i,
    );
    expect(md.indexOf(USER_START)).toBeLessThan(md.indexOf(USER_END));
  });

  test("board start map is short and points to complete stage detail", () => {
    const md = renderAgentsMd({ ...ctx, boardWorkflow: true });
    expect(md).toContain("## Start here");
    expect(md).toContain("circuit_source");
    expect(md).toContain("| `circuit.netlist.json` | Source for `circuit_build`, when that path is used. |");
    expect(md).toContain("fabdesk://docs/board-workflow");
    expect(md).not.toContain("### Working rules");
    expect(md.length).toBeLessThan(9000);
    expect(md).toContain("## Other toolsets");
    expect(md).not.toContain("## Off-board parts");
    expect(md).not.toContain("## Shopping list");
    const neutral = md.replace(/## Start here[\s\S]*?(?=## Other toolsets)/, "");
    expect(neutral).not.toMatch(/workflow|must use|should use|prefer|retry|repeat until|run .* first|stopping policy/i);
  });

  test("no start map or workflow resource pointer without board tools", () => {
    const md = renderAgentsMd({ ...ctx, boardWorkflow: false });
    expect(md).not.toContain("## Start here");
    expect(md).not.toContain("fabdesk://docs/board-workflow");
    expect(md).not.toContain("`board_check`");
  });

  test("new-board choices have matching factual descriptions without recommendations", () => {
    const md = renderAgentsMd({ ...ctx, boardWorkflow: true });
    const row = md.split("\n").find((line) => line.startsWith("| New board |"))!;
    expect(row.split("|")[2]?.trim()).toBe("Choose `circuit_build` or `schematic_edit`; get the board ready");
    const inputs = md.split("### New-board inputs\n")[1]!.split(/\n(?:### |\| Request)/)[0]!;
    const descriptions = inputs.split("\n").filter((line) => /^- `(circuit_build|schematic_edit)`:/.test(line));
    // Closed factual descriptions for both choices catch added steering adjectives
    // (including "slower") rather than trying to blacklist four words.
    expect(descriptions).toEqual([
      '- `circuit_build`: creates the schematic and board, including an outline when none exists and board dimensions or outline points are supplied, and uses `board.placements` for placed parts.',
      '- `schematic_edit`: edits the schematic only; `pcb_update_from_schematic` `{"apply": true}` brings parts to the board, `pcb_define_outline` sets the outline and `pcb_place` positions parts.',
    ]);
    const newBoardText = inputs + row;
    expect(newBoardText).not.toMatch(/prefer|recommend|instead|fallback|usual|default|faster|slower|simpler|easier|better|best|quick|easy|ideal/i);
  });

  test("board-ready requirement precedes the first board_check in reading order", () => {
    const md = renderAgentsMd({ ...ctx, boardWorkflow: true });
    const ready = md.match(/Before the first `board_check`,[^\n]+/);
    expect(ready).not.toBeNull();
    expect(ready![0]).toMatch(/parts, an outline, and connectors and other fixed parts in their intended positions/);
    expect(ready![0]).toMatch(/because `board_check` records those positions as anchors/);
    expect(ready!.index).toBe(md.indexOf("`board_check`") - "Before the first ".length);
    expect(md.indexOf("### New-board inputs")).toBeLessThan(ready!.index!);
  });

  test("both new-board paths explain preparation before the board_check sequence", () => {
    const md = renderAgentsMd({ ...ctx, boardWorkflow: true });
    const row = md.split("\n").find((line) => line.startsWith("| New board |"))!;
    expect(row).toContain("`board_check` → layout → review → `render_publish`");
    const sequence = md.indexOf(row);
    const inputs = md.slice(md.indexOf("### New-board inputs"), sequence);
    expect(inputs).toMatch(/`circuit_build`[^\n]*schematic and board[^\n]*outline when none exists[^\n]*`board.placements`/);
    const schematic = inputs.split("- `schematic_edit`:")[1]?.split("\n")[0] ?? "";
    expect(schematic).toMatch(/schematic only[^\n]*`pcb_update_from_schematic` `{"apply": true}`[^\n]*brings parts to the board/);
    expect(schematic).toMatch(/`pcb_define_outline` sets the outline/);
    expect(schematic).toMatch(/`pcb_place` positions parts/);
  });

  test("resource pointer names the configured server without client-specific syntax", () => {
    const md = renderAgentsMd({ ...ctx, boardWorkflow: true, mcpServerName: "custom-pcb" });
    const detail = md.split("### More detail")[1]?.split("## Other toolsets")[0];
    expect(detail).toContain("fabdesk://docs/board-workflow");
    expect(detail).toContain("`custom-pcb`");
    expect(detail).not.toContain("read_mcp_resource");
  });

  test("experimental modes keep their output even with board tools registered", () => {
    for (const interfaceMode of ["substrate", "programmable"] as const) {
      expect(renderAgentsMd({ ...ctx, interfaceMode, boardWorkflow: true })).toBe(
        renderAgentsMd({ ...ctx, interfaceMode, boardWorkflow: false }),
      );
    }
  });

  test("docs/board-workflow.md is the same text as the complete workflow constant", () => {
    const doc = readFileSync(new URL("../../../docs/board-workflow.md", import.meta.url), "utf8");
    expect(doc.replace(/^# /, "## ")).toBe(BOARD_WORKFLOW_MD);
  });

  test("sandboxed shell guidance suppresses the authenticated CLI instructions", () => {
    const md = renderAgentsMd({ ...ctx, fabdeskCli: "/active/fabpcb", fabdeskCliUnavailableReason: "Use MCP capability_call because shell loopback is unavailable." });
    expect(md).toContain("Use MCP capability_call");
    expect(md).not.toContain('"$FABDESK_CLI" tool');
    expect(renderAgentsMd({ ...ctx, fabdeskCli: "/active/fabpcb" })).toContain('"$FABDESK_CLI" tool describe');
  });

  test("renders neutral direct-IPC discovery only for the programmable interface", () => {
    const md = renderAgentsMd({ ...ctx, interfaceMode: "programmable" });
    expect(md).toContain("No Fabdesk MCP design tools are exposed");
    expect(md).toContain("fabpcb ipc search --query <text>");
    expect(md).toContain("fabpcb ipc describe <operation-id>");
    expect(md).toContain("fabpcb ipc call <operation-id> --request '<json-object>'");
    expect(md).toContain("optional and may be mixed");
    expect(md).not.toMatch(
      /must use|should use|prefer|retry|repeat until|run .* first|stopping policy/i,
    );
  });

  test("keeps direct IPC absent from the substrate control", () => {
    expect(renderAgentsMd({ ...ctx, interfaceMode: "substrate" })).not.toContain("fabpcb ipc");
    expect(renderAgentsMd({ ...ctx, interfaceMode: "substrate" })).not.toContain(
      "## Shopping list",
    );
  });

  test("handles missing sketches and unconstrained size", () => {
    const md = renderAgentsMd({ ...ctx, sketches: [], board: { layers: 4 }, toolsMarkdown: "" });
    expect(md).toContain("No sketches attached");
    expect(md).toContain("not fixed");
    expect(md).not.toContain("tool documentation");
  });
});

describe("writeAgentDocs", () => {
  test("writes AGENTS.md + CLAUDE.md and preserves the user section across regeneration", async () => {
    const dir = mkdtempSync(join(tmpdir(), "fabdesk-docs-"));
    try {
      await writeAgentDocs(dir, ctx);
      expect(readFileSync(join(dir, "CLAUDE.md"), "utf8")).toBe("@AGENTS.md\n");
      const first = readFileSync(join(dir, "AGENTS.md"), "utf8");
      expect(first).toContain("Blinky");

      // User edits the preserved section (and, wrongly, something outside it).
      const edited = first
        .replace(
          /<!-- fabdesk:user-start -->[\s\S]*<!-- fabdesk:user-end -->/,
          `${USER_START}\nUse 0603 passives only.\n${USER_END}`,
        )
        .replace("Copper layers: 2", "Copper layers: 99");
      writeFileSync(join(dir, "AGENTS.md"), edited);
      writeFileSync(join(dir, "CLAUDE.md"), "stale");

      await writeAgentDocs(dir, { ...ctx, projectName: "Blinky v2" });
      const second = readFileSync(join(dir, "AGENTS.md"), "utf8");
      expect(second).toContain("# Blinky v2 — fabPlane project");
      expect(second).toContain("Use 0603 passives only.");
      expect(second).toContain("Copper layers: 2");
      expect(second).not.toContain("Copper layers: 99");
      expect(readFileSync(join(dir, "CLAUDE.md"), "utf8")).toBe("@AGENTS.md\n");
      expect(extractUserSection(second)).toBe("Use 0603 passives only.");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  test("extractUserSection returns undefined when markers are absent or broken", () => {
    expect(extractUserSection(undefined)).toBeUndefined();
    expect(extractUserSection("# hand written")).toBeUndefined();
    expect(extractUserSection(`${USER_START}\nno end`)).toBeUndefined();
  });
});
